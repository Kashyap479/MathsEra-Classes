create table if not exists public.fees (
  id bigint generated by default as identity primary key,
  title text not null, course text, amount text, duration text,
  payment_note text, description text, published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.achievements (
  id bigint generated by default as identity primary key,
  student_name text not null, class_name text, exam text, marks text,
  percentage text, rank text, achievement text, year text, photo_url text,
  published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null, description text, event_date text, event_time text,
  venue text, eligibility text, registration_fee text, registration_url text,
  prizes text, rules text, status text, poster_url text,
  published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null, type text, body text, publish_date text,
  published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.posters (
  id bigint generated by default as identity primary key,
  title text not null, description text, image_url text,
  button_text text, button_url text,
  published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
