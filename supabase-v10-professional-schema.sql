  title text not null, class_name text, subject text, board text,
  description text, duration text, whatsapp_url text,
  published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.batches (
  id bigint generated by default as identity primary key,
  title text not null, class_name text, subject text, board text,
  start_date text, timing text, duration text, fee text, status text,
  description text, published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
